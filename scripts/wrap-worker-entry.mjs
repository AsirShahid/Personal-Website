#!/usr/bin/env node
// Wrap the Astro Cloudflare entry with the canonical-URL / 410 rules.
//
// The @astrojs/cloudflare adapter always writes its own dist/server/entry.mjs
// and ignores a custom `main` in wrangler.jsonc, so the wrapper is installed
// after the build:
//
//   dist/server/entry.mjs        -> `export { default } from "./seo-entry.mjs"`
//   dist/server/entry.astro.mjs  -> the adapter's original entry
//   dist/server/seo-entry.mjs    -> src/worker/seo-entry.mjs
//   dist/server/canonical.mjs    -> src/worker/canonical.mjs
//
// Idempotent: re-running rebuilds the same layout from the preserved original.

import { copyFile, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const serverDir = join(root, "dist", "server");
const entry = join(serverDir, "entry.mjs");
const original = join(serverDir, "entry.astro.mjs");

const exists = async (path) => {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
};

if (!(await exists(entry))) {
  console.error(`wrap-worker-entry: ${entry} is missing; run astro build first`);
  process.exit(1);
}

const current = await readFile(entry, "utf8");
const alreadyWrapped = current.includes('from "./seo-entry.mjs"');

if (!alreadyWrapped) {
  await copyFile(entry, original);
}

await copyFile(join(root, "src", "worker", "seo-entry.mjs"), join(serverDir, "seo-entry.mjs"));
await copyFile(join(root, "src", "worker", "canonical.mjs"), join(serverDir, "canonical.mjs"));

if (!alreadyWrapped) {
  await writeFile(
    entry,
    '// Generated by scripts/wrap-worker-entry.mjs.\n' +
      'export { default } from "./seo-entry.mjs";\n',
  );
}

console.log("wrap-worker-entry: dist/server/entry.mjs now runs the asir.dev URL rules");
